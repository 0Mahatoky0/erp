-- Bloc 2 - Recrutement
-- Cette migration ne modifie aucune table du bloc 1.
-- Contrat V1 requis :
--   demande_recrutement_poste(id_demande_poste)
--   utilisateur(id_utilisateur)
--   statut ACCEPTEE pour une demande autorisant le recrutement.

CREATE TABLE offre_emploi (
    id_offre BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_demande_poste BIGINT NOT NULL REFERENCES demande_recrutement_poste(id_demande_poste),
    id_utilisateur_createur BIGINT NOT NULL REFERENCES utilisateur(id_utilisateur),
    reference VARCHAR(50) NOT NULL UNIQUE,
    titre VARCHAR(150) NOT NULL,
    description TEXT NOT NULL,
    profil_recherche TEXT NOT NULL,
    lieu_travail VARCHAR(255),
    type_contrat VARCHAR(50),
    effectif_recherche INTEGER NOT NULL,
    salaire_min NUMERIC(15,2),
    salaire_max NUMERIC(15,2),
    mode_selection TEXT NOT NULL,
    statut VARCHAR(20) NOT NULL DEFAULT 'BROUILLON',
    date_publication TIMESTAMP,
    date_limite_candidature TIMESTAMP,
    date_cloture TIMESTAMP,
    date_creation TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_b2_offre_effectif CHECK (effectif_recherche > 0),
    CONSTRAINT chk_b2_offre_salaires CHECK (
        (salaire_min IS NULL OR salaire_min >= 0)
        AND (salaire_max IS NULL OR salaire_max >= 0)
        AND (salaire_min IS NULL OR salaire_max IS NULL OR salaire_max >= salaire_min)
    ),
    CONSTRAINT chk_b2_offre_statut CHECK (statut IN ('BROUILLON', 'PUBLIEE', 'CLOTUREE', 'ANNULEE')),
    CONSTRAINT chk_b2_offre_publication CHECK (statut NOT IN ('PUBLIEE', 'CLOTUREE') OR date_publication IS NOT NULL),
    CONSTRAINT chk_b2_offre_date_limite CHECK (
        date_limite_candidature IS NULL OR date_publication IS NULL OR date_limite_candidature >= date_publication
    ),
    CONSTRAINT chk_b2_offre_date_cloture CHECK (
        date_cloture IS NULL OR (date_publication IS NOT NULL AND date_cloture >= date_publication)
    ),
    CONSTRAINT chk_b2_offre_cloturee CHECK (statut <> 'CLOTUREE' OR date_cloture IS NOT NULL)
);

CREATE INDEX idx_b2_offre_besoin ON offre_emploi(id_demande_poste);
CREATE INDEX idx_b2_offre_statut ON offre_emploi(statut);

CREATE TABLE candidat (
    id_candidat BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR(100) NOT NULL,
    prenom VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL,
    telephone VARCHAR(30),
    adresse TEXT,
    date_creation TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_b2_candidat_email_non_vide CHECK (LENGTH(TRIM(email)) > 0)
);

CREATE UNIQUE INDEX uq_b2_candidat_email ON candidat(LOWER(TRIM(email)));

CREATE TABLE candidature (
    id_candidature BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_offre BIGINT NOT NULL REFERENCES offre_emploi(id_offre),
    id_candidat BIGINT NOT NULL REFERENCES candidat(id_candidat),
    message_candidat TEXT,
    source VARCHAR(100),
    statut VARCHAR(30) NOT NULL DEFAULT 'RECUE',
    date_candidature TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_b2_candidature_offre_candidat UNIQUE (id_offre, id_candidat),
    CONSTRAINT chk_b2_candidature_statut CHECK (
        statut IN ('RECUE', 'EN_ETUDE', 'PRESELECTIONNEE', 'EN_EVALUATION',
                   'LISTE_ATTENTE', 'RETENUE', 'REFUSEE', 'RETIREE')
    )
);

CREATE INDEX idx_b2_candidature_offre_statut ON candidature(id_offre, statut);
CREATE INDEX idx_b2_candidature_candidat ON candidature(id_candidat);

CREATE TABLE document_candidature (
    id_document BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_candidature BIGINT NOT NULL REFERENCES candidature(id_candidature),
    type_document VARCHAR(30) NOT NULL,
    nom_fichier VARCHAR(255) NOT NULL,
    cle_stockage TEXT NOT NULL UNIQUE,
    type_mime VARCHAR(150) NOT NULL,
    taille_octets BIGINT NOT NULL,
    date_depot TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_b2_document_type CHECK (
        type_document IN ('CV', 'LETTRE_MOTIVATION', 'DIPLOME', 'CERTIFICAT', 'AUTRE')
    ),
    CONSTRAINT chk_b2_document_taille CHECK (taille_octets > 0)
);

CREATE INDEX idx_b2_document_candidature ON document_candidature(id_candidature);

CREATE TABLE entretien (
    id_entretien BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_candidature BIGINT NOT NULL REFERENCES candidature(id_candidature),
    id_utilisateur_organisateur BIGINT NOT NULL REFERENCES utilisateur(id_utilisateur),
    type_entretien VARCHAR(30) NOT NULL,
    date_debut TIMESTAMP NOT NULL,
    date_fin TIMESTAMP NOT NULL,
    lieu VARCHAR(255),
    lien_visio TEXT,
    statut VARCHAR(20) NOT NULL DEFAULT 'PLANIFIE',
    commentaire TEXT,
    date_creation TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_b2_entretien_type CHECK (type_entretien IN ('RH', 'TECHNIQUE', 'MANAGER', 'AUTRE')),
    CONSTRAINT chk_b2_entretien_dates CHECK (date_fin > date_debut),
    CONSTRAINT chk_b2_entretien_statut CHECK (statut IN ('PLANIFIE', 'REALISE', 'ANNULE', 'ABSENT')),
    CONSTRAINT uq_b2_entretien_candidature UNIQUE (id_entretien, id_candidature)
);

CREATE INDEX idx_b2_entretien_candidature ON entretien(id_candidature);
CREATE INDEX idx_b2_entretien_date ON entretien(date_debut);

CREATE TABLE entretien_participant (
    id_entretien BIGINT NOT NULL REFERENCES entretien(id_entretien),
    id_utilisateur BIGINT NOT NULL REFERENCES utilisateur(id_utilisateur),
    PRIMARY KEY (id_entretien, id_utilisateur)
);

CREATE TABLE test_recrutement (
    id_test BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_offre BIGINT NOT NULL REFERENCES offre_emploi(id_offre),
    titre VARCHAR(150) NOT NULL,
    description TEXT,
    duree_minutes INTEGER,
    note_max NUMERIC(8,2) NOT NULL DEFAULT 20,
    date_creation TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_b2_test_duree CHECK (duree_minutes IS NULL OR duree_minutes > 0),
    CONSTRAINT chk_b2_test_note_max CHECK (note_max > 0)
);

CREATE INDEX idx_b2_test_offre ON test_recrutement(id_offre);

CREATE TABLE passage_test (
    id_passage BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_test BIGINT NOT NULL REFERENCES test_recrutement(id_test),
    id_candidature BIGINT NOT NULL REFERENCES candidature(id_candidature),
    numero_tentative INTEGER NOT NULL DEFAULT 1,
    date_prevue TIMESTAMP,
    date_debut TIMESTAMP,
    date_fin TIMESTAMP,
    statut VARCHAR(20) NOT NULL DEFAULT 'PLANIFIE',
    cle_stockage_reponse TEXT,
    commentaire TEXT,
    CONSTRAINT uq_b2_passage_tentative UNIQUE (id_test, id_candidature, numero_tentative),
    CONSTRAINT chk_b2_passage_tentative CHECK (numero_tentative > 0),
    CONSTRAINT chk_b2_passage_dates CHECK (
        date_fin IS NULL OR (date_debut IS NOT NULL AND date_fin >= date_debut)
    ),
    CONSTRAINT chk_b2_passage_statut CHECK (
        statut IN ('PLANIFIE', 'EN_COURS', 'TERMINE', 'ANNULE', 'ABSENT')
    ),
    CONSTRAINT uq_b2_passage_candidature UNIQUE (id_passage, id_candidature)
);

CREATE INDEX idx_b2_passage_candidature ON passage_test(id_candidature);

CREATE TABLE evaluation_candidat (
    id_evaluation BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_candidature BIGINT NOT NULL REFERENCES candidature(id_candidature),
    id_utilisateur_evaluateur BIGINT NOT NULL REFERENCES utilisateur(id_utilisateur),
    type_evaluation VARCHAR(20) NOT NULL,
    id_entretien BIGINT,
    id_passage BIGINT,
    note NUMERIC(8,2),
    note_max NUMERIC(8,2) NOT NULL DEFAULT 20,
    appreciation VARCHAR(30) NOT NULL,
    commentaire TEXT NOT NULL,
    date_evaluation TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_b2_evaluation_entretien
        FOREIGN KEY (id_entretien, id_candidature)
        REFERENCES entretien(id_entretien, id_candidature),
    CONSTRAINT fk_b2_evaluation_passage
        FOREIGN KEY (id_passage, id_candidature)
        REFERENCES passage_test(id_passage, id_candidature),
    CONSTRAINT chk_b2_evaluation_type CHECK (type_evaluation IN ('DOSSIER', 'ENTRETIEN', 'TEST')),
    CONSTRAINT chk_b2_evaluation_support CHECK (
        (type_evaluation = 'DOSSIER' AND id_entretien IS NULL AND id_passage IS NULL)
        OR (type_evaluation = 'ENTRETIEN' AND id_entretien IS NOT NULL AND id_passage IS NULL)
        OR (type_evaluation = 'TEST' AND id_passage IS NOT NULL AND id_entretien IS NULL)
    ),
    CONSTRAINT chk_b2_evaluation_note CHECK (
        note_max > 0 AND (note IS NULL OR (note >= 0 AND note <= note_max))
    ),
    CONSTRAINT chk_b2_evaluation_appreciation CHECK (
        appreciation IN ('FAVORABLE', 'RESERVE', 'DEFAVORABLE')
    )
);

CREATE INDEX idx_b2_evaluation_candidature ON evaluation_candidat(id_candidature);

CREATE TABLE decision_candidature (
    id_decision BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_candidature BIGINT NOT NULL REFERENCES candidature(id_candidature),
    id_utilisateur BIGINT NOT NULL REFERENCES utilisateur(id_utilisateur),
    decision VARCHAR(20) NOT NULL,
    motif TEXT NOT NULL,
    date_decision TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_b2_decision CHECK (decision IN ('RETENUE', 'REFUSEE', 'LISTE_ATTENTE'))
);

CREATE INDEX idx_b2_decision_candidature_date
    ON decision_candidature(id_candidature, date_decision, id_decision);

CREATE TABLE historique_candidature (
    id_historique BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_candidature BIGINT NOT NULL REFERENCES candidature(id_candidature),
    id_utilisateur BIGINT REFERENCES utilisateur(id_utilisateur),
    auteur_type VARCHAR(20) NOT NULL,
    ancien_statut VARCHAR(30),
    nouveau_statut VARCHAR(30) NOT NULL,
    commentaire TEXT,
    date_action TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_b2_historique_auteur CHECK (
        (auteur_type = 'UTILISATEUR' AND id_utilisateur IS NOT NULL)
        OR (auteur_type IN ('CANDIDAT', 'SYSTEME') AND id_utilisateur IS NULL)
    ),
    CONSTRAINT chk_b2_historique_ancien CHECK (
        ancien_statut IS NULL OR ancien_statut IN (
            'RECUE', 'EN_ETUDE', 'PRESELECTIONNEE', 'EN_EVALUATION',
            'LISTE_ATTENTE', 'RETENUE', 'REFUSEE', 'RETIREE'
        )
    ),
    CONSTRAINT chk_b2_historique_nouveau CHECK (
        nouveau_statut IN (
            'RECUE', 'EN_ETUDE', 'PRESELECTIONNEE', 'EN_EVALUATION',
            'LISTE_ATTENTE', 'RETENUE', 'REFUSEE', 'RETIREE'
        )
    ),
    CONSTRAINT chk_b2_historique_changement CHECK (
        ancien_statut IS NULL OR ancien_statut <> nouveau_statut
    )
);

CREATE INDEX idx_b2_historique_candidature_date
    ON historique_candidature(id_candidature, date_action);

CREATE TABLE historique_offre (
    id_historique BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_offre BIGINT NOT NULL REFERENCES offre_emploi(id_offre),
    id_utilisateur BIGINT NOT NULL REFERENCES utilisateur(id_utilisateur),
    ancien_statut VARCHAR(20),
    nouveau_statut VARCHAR(20) NOT NULL,
    commentaire TEXT,
    date_action TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_b2_historique_offre_ancien CHECK (
        ancien_statut IS NULL OR ancien_statut IN ('BROUILLON', 'PUBLIEE', 'CLOTUREE', 'ANNULEE')
    ),
    CONSTRAINT chk_b2_historique_offre_nouveau CHECK (
        nouveau_statut IN ('BROUILLON', 'PUBLIEE', 'CLOTUREE', 'ANNULEE')
    ),
    CONSTRAINT chk_b2_historique_offre_changement CHECK (
        ancien_statut IS NULL OR ancien_statut <> nouveau_statut
    )
);

CREATE INDEX idx_b2_historique_offre_date
    ON historique_offre(id_offre, date_action);

CREATE FUNCTION b2_actualiser_date_modification()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.date_modification := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_b2_offre_modification
BEFORE UPDATE ON offre_emploi
FOR EACH ROW EXECUTE FUNCTION b2_actualiser_date_modification();

CREATE TRIGGER trg_b2_candidat_modification
BEFORE UPDATE ON candidat
FOR EACH ROW EXECUTE FUNCTION b2_actualiser_date_modification();

CREATE TRIGGER trg_b2_candidature_modification
BEFORE UPDATE ON candidature
FOR EACH ROW EXECUTE FUNCTION b2_actualiser_date_modification();

CREATE TRIGGER trg_b2_entretien_modification
BEFORE UPDATE ON entretien
FOR EACH ROW EXECUTE FUNCTION b2_actualiser_date_modification();
