-- ---------------------------------------------------------------------
-- 1. Contrat : motif d'annulation, dates de fin de vie.
-- ---------------------------------------------------------------------
ALTER TABLE contrat ADD COLUMN IF NOT EXISTS motif_annulation TEXT;
ALTER TABLE contrat ADD COLUMN IF NOT EXISTS date_annulation TIMESTAMP;
ALTER TABLE contrat ADD COLUMN IF NOT EXISTS date_cloture TIMESTAMP;

CREATE INDEX IF NOT EXISTS idx_contrat_execution ON contrat(statut_execution);
CREATE INDEX IF NOT EXISTS idx_contrat_fin_prevue ON contrat(date_fin_prevue);
CREATE INDEX IF NOT EXISTS idx_contrat_periode_essai ON contrat(fin_periode_essai);

-- ---------------------------------------------------------------------
-- 2. Avenant : modification d'un contrat signe, historisee et versionnee.
--    Les valeurs avant/apres sont conservees (RG-B4-01, RG-B4-05).
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS avenant (
    id_avenant          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_contrat          BIGINT NOT NULL REFERENCES contrat(id_contrat),
    numero              VARCHAR(40) NOT NULL,
    type                VARCHAR(20) NOT NULL,
    date_effet          DATE NOT NULL,
    anciennes_valeurs   TEXT,
    nouvelles_valeurs   TEXT,
    nouveau_salaire     NUMERIC(15,2),
    nouvelle_date_fin   DATE,
    nouveaux_horaires   TEXT,
    nouveau_lieu        VARCHAR(150),
    id_document         BIGINT REFERENCES document_employe(id_document),
    etat                VARCHAR(20) NOT NULL DEFAULT 'CREE',
    date_signature      TIMESTAMP,
    signataire_id       BIGINT REFERENCES utilisateur(id_utilisateur),
    date_creation       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_avenant_numero UNIQUE (id_contrat, numero),
    CONSTRAINT chk_avenant_type CHECK (
        type IN ('SALAIRE', 'POSTE', 'HORAIRES', 'LIEU', 'DUREE', 'AUTRE')
    ),
    CONSTRAINT chk_avenant_etat CHECK (etat IN ('CREE', 'SIGNE', 'VALIDE')),
    CONSTRAINT chk_avenant_salaire CHECK (
        nouveau_salaire IS NULL OR nouveau_salaire >= 0
    )
);

CREATE INDEX IF NOT EXISTS idx_avenant_contrat ON avenant(id_contrat);
CREATE INDEX IF NOT EXISTS idx_avenant_etat ON avenant(etat);

-- ---------------------------------------------------------------------
-- 3. Onboarding : tracabilite de la date de cloture du parcours.
-- ---------------------------------------------------------------------
ALTER TABLE onboarding ADD COLUMN IF NOT EXISTS date_cloture TIMESTAMP;
