-- ---------------------------------------------------------------------
-- 6. Notifications internes : relances, escalades et alertes.
--    Aucun envoi externe n'est suppose : la table sert de boite d'envoi
--    consultable par les equipes (un connecteur email/SMS pourra la lire).
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS notification (
    id_notification    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type               VARCHAR(40) NOT NULL,
    niveau             VARCHAR(20) NOT NULL DEFAULT 'INFO',
    message            TEXT NOT NULL,
    id_contrat         BIGINT REFERENCES contrat(id_contrat),
    id_employe         BIGINT REFERENCES employe(id_employe),
    id_tache           BIGINT REFERENCES onboarding_tache(id_tache),
    destinataire_role  VARCHAR(30),
    echeance           DATE,
    statut             VARCHAR(20) NOT NULL DEFAULT 'A_ENVOYER',
    date_creation      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_envoi         TIMESTAMP,
    date_lecture       TIMESTAMP,
    CONSTRAINT chk_notification_niveau CHECK (
        niveau IN ('INFO', 'ATTENTION', 'DANGER')
    ),
    CONSTRAINT chk_notification_statut CHECK (
        statut IN ('A_ENVOYER', 'ENVOYEE', 'LUE')
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_notification_evenement
    ON notification (
        type,
        COALESCE(id_contrat, 0),
        COALESCE(id_tache, 0),
        COALESCE(destinataire_role, ''),
        COALESCE(echeance, DATE '1900-01-01')
    );

CREATE INDEX IF NOT EXISTS idx_notification_statut ON notification(statut, date_creation);
CREATE INDEX IF NOT EXISTS idx_notification_contrat ON notification(id_contrat);
