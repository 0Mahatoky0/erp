ALTER TABLE contrat ADD COLUMN IF NOT EXISTS ip_signature_employeur VARCHAR(64);
ALTER TABLE contrat ADD COLUMN IF NOT EXISTS decision_fin_essai VARCHAR(20);
ALTER TABLE contrat ADD COLUMN IF NOT EXISTS date_decision_fin_essai DATE;
ALTER TABLE contrat ADD COLUMN IF NOT EXISTS id_utilisateur_decision_fin_essai BIGINT
    REFERENCES utilisateur(id_utilisateur);

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'chk_contrat_decision_fin_essai'
    ) THEN
        ALTER TABLE contrat ADD CONSTRAINT chk_contrat_decision_fin_essai
            CHECK (decision_fin_essai IS NULL
                   OR decision_fin_essai IN ('CONFIRMATION', 'RUPTURE'));
    END IF;
END $$;

