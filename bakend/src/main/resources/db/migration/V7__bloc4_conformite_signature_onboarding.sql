CREATE TABLE IF NOT EXISTS onboarding_modele (
    id_modele          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code               VARCHAR(50) NOT NULL UNIQUE,
    libelle            VARCHAR(200) NOT NULL,
    type_contrat       VARCHAR(30),
    categorie_poste    VARCHAR(50),
    site               VARCHAR(150),
    actif              BOOLEAN NOT NULL DEFAULT TRUE,
    date_creation      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS onboarding_modele_tache (
    id_tache_modele        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_modele              BIGINT NOT NULL REFERENCES onboarding_modele(id_modele) ON DELETE CASCADE,
    code                   VARCHAR(50) NOT NULL,
    libelle                VARCHAR(200) NOT NULL,
    categorie              VARCHAR(20) NOT NULL,
    responsable            VARCHAR(100),
    echeance_offset_jours  INTEGER,
    obligatoire            BOOLEAN NOT NULL DEFAULT TRUE,
    bloquante              BOOLEAN NOT NULL DEFAULT FALSE,
    depend_code            VARCHAR(50),
    CONSTRAINT uq_modele_tache_code UNIQUE (id_modele, code),
    CONSTRAINT chk_modele_tache_categorie CHECK (
        categorie IN ('ADMIN', 'IT', 'MATERIEL', 'ACCES', 'FORMATION', 'PAIE', 'SECURITE')
    )
);

