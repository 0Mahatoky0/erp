CREATE TABLE incident (
    id_incident BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference VARCHAR(30) NOT NULL UNIQUE,
    declarant_id BIGINT NOT NULL,
    date_declaration TIMESTAMP NOT NULL,
    date_faits DATE NOT NULL,
    date_connaissance DATE NOT NULL,
    lieu VARCHAR(200),
    description TEXT NOT NULL,
    categorie VARCHAR(40) NOT NULL,
    gravite_initiale VARCHAR(20) NOT NULL,
    gravite_retenue VARCHAR(20),
    statut VARCHAR(30) NOT NULL,
    motif_classement TEXT,
    date_qualification TIMESTAMP,
    qualifie_par BIGINT,
    version INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE incident_employe (
    id_incident BIGINT NOT NULL,
    id_employe BIGINT NOT NULL,
    PRIMARY KEY (id_incident, id_employe)
);

CREATE TABLE incident_temoin (
    id_temoin BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_incident BIGINT NOT NULL,
    id_employe BIGINT NOT NULL,
    protege BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE procedure_disciplinaire (
    id_procedure BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference VARCHAR(30) NOT NULL UNIQUE,
    id_incident BIGINT NOT NULL,
    id_employe BIGINT NOT NULL,
    instructeur_id BIGINT NOT NULL,
    decideur_id BIGINT NOT NULL,
    date_ouverture TIMESTAMP NOT NULL,
    date_limite_prescription DATE NOT NULL,
    mise_a_pied BOOLEAN NOT NULL DEFAULT FALSE,
    mise_a_pied_debut DATE,
    mise_a_pied_fin DATE,
    mise_a_pied_remuneree BOOLEAN,
    statut VARCHAR(30) NOT NULL,
    decision VARCHAR(40),
    motivation TEXT,
    pieces_referencees TEXT,
    date_decision TIMESTAMP,
    date_cloture TIMESTAMP,
    version INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE etape_procedure (
    id_etape BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_procedure BIGINT NOT NULL,
    type VARCHAR(40) NOT NULL,
    date_etape TIMESTAMP NOT NULL,
    acteur_id BIGINT NOT NULL,
    mode_remise VARCHAR(50),
    preuve VARCHAR(255),
    delai_reponse_jours INTEGER,
    date_limite TIMESTAMP,
    id_document BIGINT,
    commentaire TEXT
);

CREATE TABLE sanction_disciplinaire (
    id_sanction BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_procedure BIGINT NOT NULL,
    id_employe BIGINT NOT NULL,
    type VARCHAR(50) NOT NULL,
    date_notification TIMESTAMP NOT NULL,
    date_effet DATE NOT NULL,
    duree_jours INTEGER,
    motif TEXT NOT NULL,
    base_reglement VARCHAR(100) NOT NULL,
    statut VARCHAR(25) NOT NULL,
    date_effacement DATE NOT NULL,
    impact_paie_jours NUMERIC(6,2),
    version INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE piece_disciplinaire (
    id_piece BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_incident BIGINT,
    id_procedure BIGINT,
    type VARCHAR(40) NOT NULL,
    fichier VARCHAR(500) NOT NULL,
    hash_sha256 VARCHAR(64) NOT NULL,
    version INTEGER NOT NULL,
    auteur_id BIGINT NOT NULL,
    date_ajout TIMESTAMP NOT NULL,
    confidentialite VARCHAR(30) NOT NULL DEFAULT 'TRES_CONFIDENTIEL'
);

CREATE TABLE acces_disciplinaire (
    id_acces BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_incident BIGINT,
    id_procedure BIGINT,
    utilisateur_id BIGINT NOT NULL,
    niveau VARCHAR(30) NOT NULL,
    motif TEXT NOT NULL,
    accorde_par_id BIGINT NOT NULL,
    date_debut TIMESTAMP NOT NULL,
    date_fin TIMESTAMP,
    actif BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE journal_discipline (
    id_journal BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_action TIMESTAMP NOT NULL,
    utilisateur_id BIGINT NOT NULL,
    action VARCHAR(40) NOT NULL,
    ressource VARCHAR(60) NOT NULL,
    id_ressource BIGINT,
    motif TEXT,
    adresse_ip VARCHAR(64),
    details TEXT
);

CREATE TABLE absence_disciplinaire (
    id_absence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sanction BIGINT NOT NULL,
    id_employe BIGINT NOT NULL,
    date_debut DATE NOT NULL,
    date_fin DATE NOT NULL,
    jours NUMERIC(6,2) NOT NULL,
    remuneree BOOLEAN NOT NULL DEFAULT TRUE,
    motif VARCHAR(150) NOT NULL,
    traitee_paie BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_incident_date_connaissance ON incident(date_connaissance);
CREATE INDEX idx_procedure_employe ON procedure_disciplinaire(id_employe);
CREATE INDEX idx_procedure_statut ON procedure_disciplinaire(statut);
CREATE INDEX idx_etape_procedure ON etape_procedure(id_procedure);
CREATE INDEX idx_sanction_employe ON sanction_disciplinaire(id_employe);
CREATE INDEX idx_journal_discipline_date ON journal_discipline(date_action);
CREATE INDEX idx_absence_periode ON absence_disciplinaire(date_debut, date_fin);
