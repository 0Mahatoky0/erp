CREATE TABLE parametre_paie (
    id_parametre BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    taux_cotisations_salariales NUMERIC(8,5),
    taux_cotisations_patronales NUMERIC(8,5),
    taux_irsa NUMERIC(8,5),
    actif BOOLEAN NOT NULL DEFAULT TRUE,
    date_modification TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE periode_paie (
    id_periode BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mois DATE NOT NULL UNIQUE,
    statut VARCHAR(20) NOT NULL DEFAULT 'BROUILLON',
    date_creation TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_cloture TIMESTAMP,
    CONSTRAINT chk_periode_paie_statut CHECK (statut IN ('BROUILLON', 'CALCULEE', 'CLOTUREE'))
);

CREATE TABLE bulletin_paie (
    id_bulletin BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_periode BIGINT NOT NULL REFERENCES periode_paie(id_periode),
    id_employe BIGINT NOT NULL REFERENCES employe(id_employe),
    salaire_brut NUMERIC(15,2) NOT NULL,
    cotisations_salariales NUMERIC(15,2) NOT NULL,
    impot NUMERIC(15,2) NOT NULL,
    retenues NUMERIC(15,2) NOT NULL DEFAULT 0,
    salaire_net NUMERIC(15,2) NOT NULL,
    cotisations_patronales NUMERIC(15,2) NOT NULL,
    statut VARCHAR(20) NOT NULL DEFAULT 'BROUILLON',
    date_creation TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_validation TIMESTAMP,
    CONSTRAINT uq_bulletin_periode_employe UNIQUE (id_periode, id_employe),
    CONSTRAINT chk_bulletin_paie_statut CHECK (statut IN ('BROUILLON', 'VALIDE', 'ANNULE'))
);
