CREATE TABLE competence (
    id_competence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    libelle VARCHAR(150) NOT NULL,
    description TEXT,
    categorie VARCHAR(30) NOT NULL,
    echelle TEXT,
    duree_validite_mois INT,
    actif BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE poste_competence (
    id_poste_competence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_poste BIGINT NOT NULL,
    id_competence BIGINT NOT NULL,
    niveau_requis INT NOT NULL,
    poids INT NOT NULL,
    CONSTRAINT uq_poste_competence UNIQUE (id_poste, id_competence),
    CONSTRAINT chk_poste_competence_niveau CHECK (niveau_requis BETWEEN 1 AND 5),
    CONSTRAINT chk_poste_competence_poids CHECK (poids BETWEEN 1 AND 3)
);

CREATE TABLE employe_competence (
    id_employe_competence BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_employe BIGINT NOT NULL,
    id_competence BIGINT NOT NULL,
    niveau_acquis INT NOT NULL,
    date_evaluation DATE NOT NULL,
    date_validite DATE,
    source VARCHAR(40) NOT NULL,
    evaluation_id BIGINT,
    formation_id BIGINT,
    valide_par_id BIGINT,
    CONSTRAINT chk_employe_competence_niveau CHECK (niveau_acquis BETWEEN 1 AND 5)
);
CREATE INDEX idx_employe_competence_employe ON employe_competence (id_employe, id_competence, date_evaluation);

CREATE TABLE campagne_evaluation (
    id_campagne BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle VARCHAR(150) NOT NULL,
    type VARCHAR(30) NOT NULL,
    periode_debut DATE NOT NULL,
    periode_fin DATE NOT NULL,
    date_ouverture DATE NOT NULL,
    date_cloture DATE NOT NULL,
    grille_json TEXT,
    ponderations_json TEXT,
    population TEXT,
    statut VARCHAR(30) NOT NULL DEFAULT 'PREPAREE',
    CONSTRAINT chk_campagne_type CHECK (type IN ('ANNUELLE', 'MI_PARCOURS', 'FIN_ESSAI')),
    CONSTRAINT chk_campagne_statut CHECK (statut IN ('PREPAREE', 'OUVERTE', 'EN_ENTRETIENS', 'CLOTUREE'))
);

CREATE TABLE objectif (
    id_objectif BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_employe BIGINT NOT NULL,
    id_campagne BIGINT NOT NULL,
    parent_objectif_id BIGINT,
    libelle VARCHAR(200) NOT NULL,
    description TEXT,
    indicateur VARCHAR(150) NOT NULL,
    unite VARCHAR(30),
    valeur_cible NUMERIC(15,2) NOT NULL,
    valeur_realisee NUMERIC(15,2),
    sens VARCHAR(25) NOT NULL DEFAULT 'PLUS_EST_MIEUX',
    poids NUMERIC(5,2) NOT NULL,
    date_echeance DATE NOT NULL,
    statut VARCHAR(25) NOT NULL DEFAULT 'DEFINI',
    taux_atteinte NUMERIC(8,4),
    version INT NOT NULL DEFAULT 1,
    motif_avenant TEXT,
    date_creation TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_objectif_poids CHECK (poids > 0 AND poids <= 100),
    CONSTRAINT chk_objectif_sens CHECK (sens IN ('PLUS_EST_MIEUX', 'MOINS_EST_MIEUX'))
);

CREATE TABLE evaluation (
    id_evaluation BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_employe BIGINT NOT NULL,
    id_campagne BIGINT NOT NULL,
    id_evaluateur BIGINT NOT NULL,
    id_valideur_n2 BIGINT,
    auto_evaluation TEXT,
    evaluation_manager TEXT,
    note_objectifs NUMERIC(5,2),
    note_competences NUMERIC(5,2),
    note_comportement NUMERIC(5,2),
    note_globale NUMERIC(5,2),
    appreciation VARCHAR(30),
    points_forts TEXT,
    axes_progres TEXT,
    date_entretien TIMESTAMP,
    commentaire_salarie TEXT,
    date_signature_salarie TIMESTAMP,
    statut VARCHAR(30) NOT NULL DEFAULT 'BROUILLON',
    version INT NOT NULL DEFAULT 1,
    motif_contestation TEXT,
    date_creation TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_cloture TIMESTAMP,
    CONSTRAINT uq_evaluation_employe_campagne_version UNIQUE (id_employe, id_campagne, version),
    CONSTRAINT chk_evaluation_statut CHECK (statut IN ('BROUILLON', 'AUTO_EVALUATION', 'EVALUATION_MANAGER',
        'ENTRETIEN', 'VALIDEE_N2', 'SIGNEE', 'CLOTUREE', 'CONTESTEE'))
);

CREATE TABLE ecart_competence (
    id_ecart BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_employe BIGINT NOT NULL,
    id_competence BIGINT NOT NULL,
    id_evaluation BIGINT NOT NULL,
    niveau_requis INT NOT NULL,
    niveau_acquis INT NOT NULL,
    ecart INT NOT NULL,
    priorite_score NUMERIC(8,2) NOT NULL,
    priorite VARCHAR(10) NOT NULL,
    statut VARCHAR(25) NOT NULL DEFAULT 'OUVERT',
    CONSTRAINT chk_ecart_statut CHECK (statut IN ('OUVERT', 'FORMATION_PLANIFIEE', 'COMBLE', 'ACCEPTE'))
);
CREATE INDEX idx_ecart_employe ON ecart_competence (id_employe, statut);

CREATE TABLE besoin_formation (
    id_besoin BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_employe BIGINT NOT NULL,
    id_competence BIGINT NOT NULL,
    niveau_cible INT NOT NULL,
    origine VARCHAR(25) NOT NULL,
    priorite VARCHAR(10) NOT NULL,
    date_cible DATE,
    budget_estime NUMERIC(15,2),
    statut VARCHAR(20) NOT NULL DEFAULT 'IDENTIFIE',
    motif_refus TEXT,
    source_evaluation_id BIGINT,
    date_creation TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_besoin_origine CHECK (origine IN ('ECART', 'EVALUATION', 'DEMANDE_SALARIE',
        'DEMANDE_MANAGER', 'OBLIGATION_LEGALE', 'EVOLUTION_POSTE')),
    CONSTRAINT chk_besoin_statut CHECK (statut IN ('IDENTIFIE', 'VALIDE', 'PLANIFIE', 'REALISE', 'ABANDONNE'))
);

CREATE TABLE formation (
    id_formation BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    titre VARCHAR(200) NOT NULL,
    type VARCHAR(20) NOT NULL,
    organisme VARCHAR(150),
    duree_h NUMERIC(8,2) NOT NULL,
    cout NUMERIC(15,2) NOT NULL,
    certifiante BOOLEAN NOT NULL DEFAULT FALSE,
    competences_visees TEXT,
    seuil_dedit NUMERIC(15,2),
    CONSTRAINT chk_formation_type CHECK (type IN ('INTERNE', 'EXTERNE', 'E_LEARNING'))
);

CREATE TABLE plan_formation (
    id_plan BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    annee INT NOT NULL,
    id_departement BIGINT NOT NULL,
    budget NUMERIC(15,2) NOT NULL,
    CONSTRAINT uq_plan_formation UNIQUE (annee, id_departement)
);

CREATE TABLE session_formation (
    id_session BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_formation BIGINT NOT NULL,
    date_debut DATE NOT NULL,
    date_fin DATE NOT NULL,
    lieu VARCHAR(150),
    capacite INT NOT NULL,
    formateur VARCHAR(150),
    cout NUMERIC(15,2) NOT NULL,
    statut VARCHAR(20) NOT NULL DEFAULT 'PLANIFIEE',
    CONSTRAINT chk_session_capacite CHECK (capacite > 0),
    CONSTRAINT chk_session_statut CHECK (statut IN ('PLANIFIEE', 'OUVERTE', 'COMPLETE', 'REALISEE', 'ANNULEE'))
);
CREATE INDEX idx_session_formation_dates ON session_formation (date_debut, date_fin);

CREATE TABLE inscription_formation (
    id_inscription BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_session BIGINT NOT NULL,
    id_employe BIGINT NOT NULL,
    date_demande TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    statut VARCHAR(25) NOT NULL DEFAULT 'DEMANDEE',
    presence_h NUMERIC(8,2),
    resultat TEXT,
    certificat_document_id BIGINT,
    id_besoin BIGINT,
    CONSTRAINT chk_inscription_statut CHECK (statut IN ('DEMANDEE', 'VALIDEE_MANAGER', 'CONFIRMEE',
        'LISTE_ATTENTE', 'PRESENT', 'ABSENT', 'ANNULEE'))
);
CREATE INDEX idx_inscription_session_statut ON inscription_formation (id_session, statut, date_demande);

CREATE TABLE evaluation_formation (
    id_evaluation_formation BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_inscription BIGINT NOT NULL,
    type VARCHAR(15) NOT NULL,
    satisfaction INT,
    acquis NUMERIC(5,2),
    transfert NUMERIC(5,2),
    commentaire TEXT,
    date_evaluation TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_evaluation_formation_type CHECK (type IN ('A_CHAUD', 'A_FROID_90J'))
);

CREATE TABLE convention_formation (
    id_convention BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_inscription BIGINT NOT NULL UNIQUE,
    cout NUMERIC(15,2) NOT NULL,
    duree_engagement_mois INT NOT NULL,
    clause_dedit TEXT NOT NULL
);
