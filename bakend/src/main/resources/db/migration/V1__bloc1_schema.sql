-- ERP - BLOC 1 : schema de la base de donnees PostgreSQL
CREATE TABLE departement (
    id_departement BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom            VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE service (
    id_service     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_departement BIGINT NOT NULL REFERENCES departement(id_departement),
    nom            VARCHAR(100) NOT NULL,
    CONSTRAINT uq_service_departement_nom UNIQUE (id_departement, nom)
);

CREATE TABLE role (
    id_role BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom    VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE utilisateur (
    id_utilisateur BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_departement  BIGINT REFERENCES departement(id_departement),
    id_role         BIGINT NOT NULL REFERENCES role(id_role),
    nom             VARCHAR(150) NOT NULL,
    email           VARCHAR(255) NOT NULL UNIQUE,
    mot_de_passe    TEXT NOT NULL,
    actif           BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE poste (
    id_poste    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_service  BIGINT NOT NULL REFERENCES service(id_service),
    intitule    VARCHAR(150) NOT NULL,
    description TEXT,
    salaire_min NUMERIC(15,2),
    salaire_max NUMERIC(15,2),
    actif       BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_poste_service_intitule UNIQUE (id_service, intitule),
    CONSTRAINT chk_poste_salaires CHECK (
        (salaire_min IS NULL OR salaire_min >= 0)
        AND (salaire_max IS NULL OR salaire_max >= 0)
        AND (salaire_min IS NULL OR salaire_max IS NULL OR salaire_max >= salaire_min)
    )
);

CREATE TABLE employe (
    id_employe     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matricule      VARCHAR(50) NOT NULL UNIQUE,
    nom            VARCHAR(100) NOT NULL,
    prenom         VARCHAR(100) NOT NULL,
    email          VARCHAR(255) UNIQUE,
    telephone      VARCHAR(30),
    date_embauche DATE,
    id_poste       BIGINT REFERENCES poste(id_poste),
    statut         VARCHAR(30) NOT NULL DEFAULT 'ACTIF',
    date_creation  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_employe_statut CHECK (statut IN ('ACTIF', 'INACTIF', 'PARTI'))
);

CREATE TABLE demande_recrutement (
    id_demande         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_utilisateur     BIGINT NOT NULL REFERENCES utilisateur(id_utilisateur),
    motif              TEXT NOT NULL,
    date_souhaitee     DATE NOT NULL,
    statut             VARCHAR(30) NOT NULL DEFAULT 'BROUILLON',
    date_creation      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_soumission    TIMESTAMP,
    CONSTRAINT chk_demande_statut CHECK (statut IN (
        'BROUILLON', 'EN_VALIDATION', 'A_CORRIGER',
        'FINALISEE', 'FINALISEE_PARTIELLE', 'REFUSEE', 'ANNULEE'
    ))
);

CREATE TABLE demande_recrutement_poste (
    id_demande_poste          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_demande                BIGINT NOT NULL REFERENCES demande_recrutement(id_demande),
    id_service                BIGINT NOT NULL REFERENCES service(id_service),
    id_poste                  BIGINT REFERENCES poste(id_poste),

    type_besoin               VARCHAR(20) NOT NULL,
    type_remplacement         VARCHAR(20),
    id_employe_remplace       BIGINT REFERENCES employe(id_employe),
    motif_remplacement        TEXT,
    date_debut_remplacement   DATE,
    date_fin_remplacement     DATE,

    intitule_demande          VARCHAR(150) NOT NULL,
    description_poste         TEXT,
    profil_recherche          TEXT,
    salaire_min_estime        NUMERIC(15,2),
    salaire_max_estime        NUMERIC(15,2),
    effectif                  INTEGER NOT NULL DEFAULT 1,
    budget_estime             NUMERIC(15,2) NOT NULL,

    statut                    VARCHAR(30) NOT NULL DEFAULT 'BROUILLON',
    date_creation             TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification         TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_soumission           TIMESTAMP,

    -- (RM-040) : episode de validation de la ligne.
    -- Chaque resoumission apres correction incremente l'episode ; les
    -- decisions de la table "validation" y sont rattachees pour qu'une
    -- meme etape ne puisse pas etre validee deux fois sur un episode.
    episode                   INTEGER NOT NULL DEFAULT 1,

    -- (RM-038) : etape du circuit a laquelle la ligne est
    -- actuellement suspendue. Necessaire pour savoir ou reprendre apres
    -- une demande de correction (le statut seul ne le dit plus).
    etape_courante            VARCHAR(20),

    CONSTRAINT chk_ligne_statut CHECK (statut IN (
        'BROUILLON', 'EN_ATTENTE_RH', 'EN_ATTENTE_FINANCE', 'EN_ATTENTE_DIRECTION',
        'A_CORRIGER', 'ACCEPTEE', 'REFUSEE', 'ANNULEE'
    )),

    CONSTRAINT chk_type_besoin CHECK (type_besoin IN ('CREATION', 'REMPLACEMENT')),

    CONSTRAINT chk_type_remplacement CHECK (
        (
            type_besoin = 'CREATION'
            AND type_remplacement IS NULL
            AND id_employe_remplace IS NULL
            AND date_debut_remplacement IS NULL
            AND date_fin_remplacement IS NULL
        )
        OR
        (
            type_besoin = 'REMPLACEMENT'
            AND type_remplacement IN ('TEMPORAIRE', 'DEFINITIF')
        )
    ),

    -- RM-028 : un remplacement temporaire exige une date de debut.
    CONSTRAINT chk_remplacement_temporaire CHECK (
        type_remplacement <> 'TEMPORAIRE'
        OR date_debut_remplacement IS NOT NULL
    ),

    -- RM-062 : ordre chronologique des dates de remplacement.
    CONSTRAINT chk_dates_remplacement CHECK (
        date_fin_remplacement IS NULL
        OR (
            date_debut_remplacement IS NOT NULL
            AND date_fin_remplacement >= date_debut_remplacement
        )
    ),

    CONSTRAINT chk_effectif CHECK (effectif > 0),

    CONSTRAINT chk_budget_estime CHECK (budget_estime >= 0),

    CONSTRAINT chk_salaire CHECK (
        (salaire_min_estime IS NULL OR salaire_min_estime >= 0)
        AND
        (salaire_max_estime IS NULL OR salaire_max_estime >= 0)
        AND
        (
            salaire_min_estime IS NULL
            OR salaire_max_estime IS NULL
            OR salaire_max_estime >= salaire_min_estime
        )
    ),

    CONSTRAINT chk_episode CHECK (episode >= 1)
);

CREATE INDEX idx_demande_poste_demande
    ON demande_recrutement_poste (id_demande);
CREATE INDEX idx_demande_poste_service
    ON demande_recrutement_poste (id_service);
CREATE INDEX idx_demande_poste_poste
    ON demande_recrutement_poste (id_poste);
CREATE INDEX idx_demande_poste_employe_remplace
    ON demande_recrutement_poste (id_employe_remplace);
CREATE INDEX idx_demande_poste_statut
    ON demande_recrutement_poste (statut);


CREATE TABLE validation (
    id_validation    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_demande_poste BIGINT NOT NULL REFERENCES demande_recrutement_poste(id_demande_poste),
    id_utilisateur   BIGINT NOT NULL REFERENCES utilisateur(id_utilisateur),
    etape            VARCHAR(20) NOT NULL,
    decision         VARCHAR(20) NOT NULL,
    commentaire      TEXT,
    date_action      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    episode          INTEGER NOT NULL DEFAULT 1,
    CONSTRAINT chk_validation_etape CHECK (etape IN ('RH', 'FINANCE', 'DIRECTION')),
    CONSTRAINT chk_validation_decision CHECK (decision IN ('APPROUVE', 'REFUSE', 'A_CORRIGER'))
);

CREATE INDEX idx_validation_demande_date
    ON validation (id_demande_poste, date_action);

-- Budgets annuels par service 
CREATE TABLE budget_service (
    id_budget_service BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_service        BIGINT NOT NULL REFERENCES service(id_service),
    exercice          INTEGER NOT NULL,
    montant_alloue    NUMERIC(15,2) NOT NULL,
    -- (RM-051) : le budget disponible se calcule a partir de
    -- l'allocation, des depenses reelles et des engagements deja reserves
    -- (montant_engage = lignes acceptees). Sans ces deux colonnes on ne
    -- saurait pas distinguer une depense d'un engagement.
    montant_depense   NUMERIC(15,2) NOT NULL DEFAULT 0,
    montant_engage    NUMERIC(15,2) NOT NULL DEFAULT 0,
    date_creation     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_budget_service_exercice UNIQUE (id_service, exercice),
    CONSTRAINT chk_budget_montant_alloue CHECK (montant_alloue >= 0),
    CONSTRAINT chk_budget_montant_depense CHECK (montant_depense >= 0),
    CONSTRAINT chk_budget_montant_engage CHECK (montant_engage >= 0)
);

-- Controle financier (RM-052 a RM-055)

CREATE TABLE verification_budget (
    id_verification     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_demande_poste    BIGINT NOT NULL REFERENCES demande_recrutement_poste(id_demande_poste),
    id_budget_service   BIGINT NOT NULL REFERENCES budget_service(id_budget_service),
    id_utilisateur      BIGINT NOT NULL REFERENCES utilisateur(id_utilisateur),
    budget_demande      NUMERIC(15,2) NOT NULL,
    budget_disponible   NUMERIC(15,2) NOT NULL,
    montant_estime      NUMERIC(15,2) NOT NULL,
    decision            VARCHAR(20) NOT NULL,
    commentaire         TEXT,
    date_verification   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    episode             INTEGER NOT NULL DEFAULT 1,
    CONSTRAINT chk_verification_budget_decision
        CHECK (decision IN ('APPROUVE', 'REFUSE', 'A_CORRIGER')),
    CONSTRAINT chk_verification_budget_montants CHECK (
        budget_demande >= 0
        AND budget_disponible >= 0
        AND montant_estime >= 0
    )
);

CREATE INDEX idx_verification_budget_demande_date
    ON verification_budget (id_demande_poste, date_verification);

-- ---------------------------------------------------------------------
-- (RM-065) : journal des changements de statut.
-- La table "validation" ne retrace que les decisions ; ce journal retrace
-- tous les changements de statut (ligne ET demande globale), y compris
-- les annulations et les resoumissions.
-- id_demande_poste IS NULL  => le changement concerne la demande globale.
-- ---------------------------------------------------------------------
CREATE TABLE historique_statut (
    id_historique    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_demande       BIGINT NOT NULL REFERENCES demande_recrutement(id_demande),
    id_demande_poste BIGINT REFERENCES demande_recrutement_poste(id_demande_poste),
    ancien_statut    VARCHAR(30),
    nouveau_statut   VARCHAR(30) NOT NULL,
    id_utilisateur   BIGINT REFERENCES utilisateur(id_utilisateur),
    commentaire       TEXT,
    date_action      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_historique_statut_demande
    ON historique_statut (id_demande, date_action);
