CREATE TABLE ligne_bulletin (
    id_ligne BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_bulletin BIGINT NOT NULL REFERENCES bulletin_paie(id_bulletin),
    code_rubrique VARCHAR(40) NOT NULL,
    libelle VARCHAR(150) NOT NULL,
    ordre INTEGER NOT NULL,
    base NUMERIC(15,2),
    taux NUMERIC(8,5),
    quantite NUMERIC(12,2),
    montant_salarial NUMERIC(15,2) NOT NULL DEFAULT 0,
    montant_patronal NUMERIC(15,2) NOT NULL DEFAULT 0,
    formule_appliquee TEXT,
    version_regle VARCHAR(50),
    sources TEXT
);

CREATE INDEX idx_ligne_bulletin_bulletin ON ligne_bulletin(id_bulletin);

CREATE TABLE fiche_paie (
    id_fiche BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_bulletin BIGINT NOT NULL UNIQUE REFERENCES bulletin_paie(id_bulletin),
    id_periode BIGINT NOT NULL REFERENCES periode_paie(id_periode),
    id_employe BIGINT NOT NULL REFERENCES employe(id_employe),
    mois DATE NOT NULL,
    numero VARCHAR(30),
    net_a_payer NUMERIC(15,2) NOT NULL,
    contenu_json TEXT NOT NULL,
    hash VARCHAR(64) NOT NULL,
    date_generation TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_fiche_paie_employe_mois ON fiche_paie(id_employe, mois);
