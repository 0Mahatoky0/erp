CREATE TABLE contrat_embauche (
    id_contrat BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proposition_embauche BIGINT NOT NULL UNIQUE REFERENCES proposition_embauche(id_proposition_embauche),
    id_candidat BIGINT NOT NULL REFERENCES candidat(id_candidat),
    id_employe BIGINT UNIQUE REFERENCES employe(id_employe),
    type_contrat VARCHAR(20) NOT NULL,
    salaire NUMERIC(15,2),
    lieu_travail VARCHAR(255),
    date_debut TIMESTAMP NOT NULL,
    date_fin TIMESTAMP,
    statut VARCHAR(20) NOT NULL DEFAULT 'PROPOSE',
    date_creation TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_reponse TIMESTAMP,
    date_validation TIMESTAMP,
    CONSTRAINT chk_contrat_type CHECK (type_contrat IN ('CDI', 'CDD')),
    CONSTRAINT chk_contrat_salaire CHECK (salaire IS NULL OR salaire >= 0),
    CONSTRAINT chk_contrat_dates CHECK (date_fin IS NULL OR date_fin >= date_debut),
    CONSTRAINT chk_contrat_cdd_date_fin CHECK (type_contrat <> 'CDD' OR date_fin IS NOT NULL),
    CONSTRAINT chk_contrat_statut CHECK (statut IN ('PROPOSE', 'ACCEPTE', 'REFUSE', 'VALIDE'))
);

CREATE INDEX idx_contrat_embauche_candidat ON contrat_embauche(id_candidat);
CREATE INDEX idx_contrat_embauche_statut ON contrat_embauche(statut);
