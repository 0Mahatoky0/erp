CREATE TABLE mouvement_carriere (
    id_mouvement BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference VARCHAR(30) NOT NULL UNIQUE,
    id_employe BIGINT NOT NULL,
    type VARCHAR(30) NOT NULL,
    initiateur VARCHAR(30) NOT NULL,
    motif VARCHAR(100) NOT NULL,
    justification TEXT NOT NULL,
    date_effet_souhaitee DATE NOT NULL,
    date_effet DATE,
    id_evaluation BIGINT,
    id_avenant BIGINT,
    documents TEXT,
    statut VARCHAR(30) NOT NULL DEFAULT 'BROUILLON',
    version INT NOT NULL DEFAULT 1,
    id_campagne BIGINT,
    id_demandeur BIGINT NOT NULL,
    id_validateur BIGINT,
    motif_refus TEXT,
    derogation_direction BOOLEAN NOT NULL DEFAULT FALSE,
    motif_derogation TEXT,
    conditions_verifiees TEXT,
    date_creation TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_decision TIMESTAMP,
    date_application TIMESTAMP,
    CONSTRAINT chk_mouvement_type CHECK (type IN ('PROMOTION', 'MUTATION', 'CHANGEMENT_POSTE',
        'CHANGEMENT_SALAIRE', 'DETACHEMENT')),
    CONSTRAINT chk_mouvement_statut CHECK (statut IN ('BROUILLON', 'SOUMIS', 'EN_VALIDATION',
        'A_COMPLETER', 'VALIDE', 'AVENANT_EN_SIGNATURE', 'PLANIFIE', 'APPLIQUE', 'CORRIGE',
        'REFUSE', 'REFUSE_PAR_SALARIE', 'ANNULE'))
);
CREATE INDEX idx_mouvement_employe_statut ON mouvement_carriere (id_employe, statut);
CREATE INDEX idx_mouvement_statut_date ON mouvement_carriere (statut, date_effet);

CREATE TABLE promotion (
    id_promotion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_mouvement BIGINT NOT NULL UNIQUE,
    nature VARCHAR(40) NOT NULL,
    id_ancien_poste BIGINT NOT NULL,
    id_nouveau_poste BIGINT NOT NULL,
    ancienne_categorie VARCHAR(50),
    nouvelle_categorie VARCHAR(50),
    ancien_echelon VARCHAR(50),
    nouveau_echelon VARCHAR(50),
    ancien_salaire NUMERIC(15, 2) NOT NULL,
    nouveau_salaire NUMERIC(15, 2) NOT NULL,
    CONSTRAINT chk_promotion_nature CHECK (nature IN ('CHANGEMENT_POSTE_SUPERIEUR',
        'CHANGEMENT_ECHELON', 'CHANGEMENT_CATEGORIE'))
);

CREATE TABLE mutation (
    id_mutation BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_mouvement BIGINT NOT NULL UNIQUE,
    type VARCHAR(30) NOT NULL,
    initiative VARCHAR(25) NOT NULL,
    id_poste_origine BIGINT,
    id_poste_destination BIGINT,
    id_service_origine BIGINT,
    id_service_destination BIGINT,
    id_lieu_origine VARCHAR(150),
    id_lieu_destination VARCHAR(150),
    id_manager_origine BIGINT,
    id_manager_destination BIGINT,
    date_retour_prevue DATE,
    clause_mobilite_verifiee BOOLEAN NOT NULL DEFAULT FALSE,
    accord_salarie_document_id BIGINT,
    indemnite_mobilite NUMERIC(15, 2),
    CONSTRAINT chk_mutation_type CHECK (type IN ('INTERNE_SERVICE', 'INTER_DEPARTEMENT',
        'GEOGRAPHIQUE', 'TEMPORAIRE', 'DETACHEMENT')),
    CONSTRAINT chk_mutation_initiative CHECK (initiative IN ('EMPLOYEUR', 'SALARIE', 'ACCORD_COMMUN'))
);

CREATE TABLE grille_salariale (
    id_grille BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categorie VARCHAR(50) NOT NULL,
    echelon VARCHAR(50) NOT NULL,
    salaire_min NUMERIC(15, 2) NOT NULL,
    salaire_max NUMERIC(15, 2) NOT NULL,
    date_effet DATE NOT NULL,
    date_fin DATE,
    CONSTRAINT chk_grille_salaire CHECK (salaire_min <= salaire_max)
);
CREATE INDEX idx_grille_version ON grille_salariale (categorie, echelon, date_effet, date_fin);

CREATE TABLE campagne_augmentation (
    id_campagne_augmentation BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    libelle VARCHAR(150) NOT NULL,
    date_effet DATE NOT NULL,
    enveloppe_budgetaire NUMERIC(15, 2) NOT NULL,
    population TEXT NOT NULL,
    regle TEXT NOT NULL,
    statut VARCHAR(20) NOT NULL DEFAULT 'SIMULEE',
    simulation TEXT,
    CONSTRAINT chk_campagne_augmentation_statut CHECK (statut IN ('SIMULEE', 'VALIDEE',
        'APPLIQUEE', 'ANNULEE'))
);
