-- =====================================================================
-- BLOC 3 : Selection et embauche (cahier SIRH, section 5)
--
-- La migration V3 ne contenait qu'une esquisse (tables sans etats, sans
-- historique et sans rattachement aux objets des blocs 4 et 5). Ce bloc
-- la remplace par le modele complet decrit dans le cahier de conception.
-- Les tables V3 sont recreees : aucune donnee metier n'existe encore.
-- =====================================================================

DROP TABLE IF EXISTS historique_contrat CASCADE;
DROP TABLE IF EXISTS contrat CASCADE;
DROP TABLE IF EXISTS validation_contrat CASCADE;
DROP TABLE IF EXISTS proposition_embauche CASCADE;
DROP TABLE IF EXISTS mode_paiement CASCADE;
DROP TABLE IF EXISTS periodicite_paie CASCADE;
DROP TABLE IF EXISTS duree_essai CASCADE;
DROP TABLE IF EXISTS type_contrat CASCADE;
DROP TABLE IF EXISTS statut CASCADE;

-- ---------------------------------------------------------------------
-- 1. Employe : dossier cree a l'acceptation, sans matricule (RG-B3-06).
--    Le matricule n'est genere qu'a la signature (bloc 4, RG-B4-06).
-- ---------------------------------------------------------------------
ALTER TABLE employe ALTER COLUMN matricule DROP NOT NULL;
ALTER TABLE employe ADD COLUMN IF NOT EXISTS id_candidat BIGINT REFERENCES candidat(id_candidat);
ALTER TABLE employe ADD COLUMN IF NOT EXISTS cin VARCHAR(50);
ALTER TABLE employe ADD COLUMN IF NOT EXISTS date_naissance DATE;
ALTER TABLE employe ADD COLUMN IF NOT EXISTS lieu_naissance VARCHAR(150);
ALTER TABLE employe ADD COLUMN IF NOT EXISTS adresse TEXT;
ALTER TABLE employe ADD COLUMN IF NOT EXISTS nationalite VARCHAR(100);
ALTER TABLE employe ADD COLUMN IF NOT EXISTS situation_familiale VARCHAR(50);
ALTER TABLE employe ADD COLUMN IF NOT EXISTS date_premiere_embauche DATE;
ALTER TABLE employe ADD COLUMN IF NOT EXISTS date_modification TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP;

CREATE UNIQUE INDEX IF NOT EXISTS uq_employe_candidat ON employe(id_candidat)
    WHERE id_candidat IS NOT NULL;

ALTER TABLE employe DROP CONSTRAINT IF EXISTS chk_employe_statut;
ALTER TABLE employe ADD CONSTRAINT chk_employe_statut
    CHECK (statut IN ('PRE_EMBAUCHE', 'ACTIF', 'INACTIF', 'PARTI', 'NON_PRIS_POSTE'));

-- Identite minimale du candidat necessaire au controle de doublon (RG-B3-08).
ALTER TABLE candidat ADD COLUMN IF NOT EXISTS cin VARCHAR(50);
ALTER TABLE candidat ADD COLUMN IF NOT EXISTS date_naissance DATE;
ALTER TABLE candidat ADD COLUMN IF NOT EXISTS statut VARCHAR(20) NOT NULL DEFAULT 'CANDIDAT';
ALTER TABLE candidat DROP CONSTRAINT IF EXISTS chk_candidat_statut;
ALTER TABLE candidat ADD CONSTRAINT chk_candidat_statut
    CHECK (statut IN ('CANDIDAT', 'EMPLOYE'));

-- ---------------------------------------------------------------------
-- 2. Candidature : nouveaux etats d'embauche (section 5.4, etape 8).
-- ---------------------------------------------------------------------
ALTER TABLE candidature DROP CONSTRAINT IF EXISTS chk_b2_candidature_statut;
ALTER TABLE candidature ADD CONSTRAINT chk_b2_candidature_statut CHECK (
    statut IN ('RECUE', 'EN_ETUDE', 'PRESELECTIONNEE', 'EN_EVALUATION',
               'LISTE_ATTENTE', 'RETENUE', 'ACCEPTEE', 'EMBAUCHEE',
               'REFUSEE', 'REFUSEE_PAR_CANDIDAT', 'EXPIREE', 'RETIREE')
);

ALTER TABLE historique_candidature DROP CONSTRAINT IF EXISTS chk_b2_historique_ancien;
ALTER TABLE historique_candidature DROP CONSTRAINT IF EXISTS chk_b2_historique_nouveau;
ALTER TABLE historique_candidature ADD CONSTRAINT chk_b2_historique_ancien CHECK (
    ancien_statut IS NULL OR ancien_statut IN (
        'RECUE', 'EN_ETUDE', 'PRESELECTIONNEE', 'EN_EVALUATION',
        'LISTE_ATTENTE', 'RETENUE', 'ACCEPTEE', 'EMBAUCHEE',
        'REFUSEE', 'REFUSEE_PAR_CANDIDAT', 'EXPIREE', 'RETIREE'
    )
);
ALTER TABLE historique_candidature ADD CONSTRAINT chk_b2_historique_nouveau CHECK (
    nouveau_statut IN (
        'RECUE', 'EN_ETUDE', 'PRESELECTIONNEE', 'EN_EVALUATION',
        'LISTE_ATTENTE', 'RETENUE', 'ACCEPTEE', 'EMBAUCHEE',
        'REFUSEE', 'REFUSEE_PAR_CANDIDAT', 'EXPIREE', 'RETIREE'
    )
);

-- Compteur d'embauches par ligne de besoin (section 5.4, etape 8).
ALTER TABLE demande_recrutement_poste
    ADD COLUMN IF NOT EXISTS nombre_pourvus INTEGER NOT NULL DEFAULT 0;
ALTER TABLE demande_recrutement_poste DROP CONSTRAINT IF EXISTS chk_nombre_pourvus;
ALTER TABLE demande_recrutement_poste ADD CONSTRAINT chk_nombre_pourvus
    CHECK (nombre_pourvus >= 0);

-- ---------------------------------------------------------------------
-- 3. Compteur de references metier (PE-AAAA-NNNN, CT-AAAA-NNNNN).
--    Une ligne par type et par annee, verrouillee en ecriture.
-- ---------------------------------------------------------------------
CREATE TABLE compteur_reference (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_compteur VARCHAR(30) NOT NULL,
    annee         INTEGER NOT NULL,
    valeur        BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_compteur_reference UNIQUE (type_compteur, annee),
    CONSTRAINT chk_compteur_valeur CHECK (valeur >= 0)
);

-- ---------------------------------------------------------------------
-- 4. Document du dossier salarie (bloc 5), y compris le contrat PDF.
-- ---------------------------------------------------------------------
CREATE TABLE document_employe (
    id_document     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_employe      BIGINT NOT NULL REFERENCES employe(id_employe),
    id_contrat      BIGINT,
    type_document   VARCHAR(40) NOT NULL,
    titre           VARCHAR(200) NOT NULL,
    nom_fichier     VARCHAR(255),
    type_mime       VARCHAR(150) NOT NULL DEFAULT 'application/pdf',
    contenu         BYTEA NOT NULL,
    hash_sha256     VARCHAR(64) NOT NULL,
    version         INTEGER NOT NULL DEFAULT 1,
    statut          VARCHAR(20) NOT NULL DEFAULT 'EN_ATTENTE',
    confidentialite VARCHAR(20) NOT NULL DEFAULT 'CONFIDENTIEL',
    date_emission   DATE,
    date_validite   DATE,
    date_creation   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_document_statut CHECK (
        statut IN ('EN_ATTENTE', 'VALIDE', 'REFUSE', 'EXPIRE', 'ARCHIVE')
    ),
    CONSTRAINT chk_document_version CHECK (version >= 1)
);

CREATE INDEX idx_document_employe ON document_employe(id_employe);
CREATE INDEX idx_document_contrat ON document_employe(id_contrat);

-- ---------------------------------------------------------------------
-- 5. Proposition d'embauche (section 5.2 et 5.3).
-- ---------------------------------------------------------------------
CREATE TABLE proposition_embauche (
    id_proposition           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reference                VARCHAR(50) NOT NULL UNIQUE,
    id_candidature           BIGINT NOT NULL REFERENCES candidature(id_candidature),
    version                  INTEGER NOT NULL DEFAULT 1,
    active                   BOOLEAN NOT NULL DEFAULT TRUE,
    id_poste                 BIGINT REFERENCES poste(id_poste),
    id_departement           BIGINT REFERENCES departement(id_departement),
    id_service               BIGINT REFERENCES service(id_service),
    id_manager               BIGINT REFERENCES utilisateur(id_utilisateur),
    type_contrat             VARCHAR(30) NOT NULL,
    duree_mois               INTEGER,
    date_debut_prevue        DATE NOT NULL,
    periode_essai_mois       INTEGER NOT NULL DEFAULT 1,
    salaire_brut_mensuel     NUMERIC(15,2) NOT NULL,
    devise                   VARCHAR(10) NOT NULL DEFAULT 'MGA',
    primes_avantages         TEXT,
    horaires                 TEXT,
    lieu_travail             VARCHAR(150),
    date_envoi               TIMESTAMP,
    date_expiration          TIMESTAMP,
    statut                   VARCHAR(30) NOT NULL DEFAULT 'BROUILLON',
    token_acceptation        VARCHAR(128) UNIQUE,
    date_reponse             TIMESTAMP,
    motif_refus              TEXT,
    preuve_reponse           VARCHAR(255),
    ip_reponse               VARCHAR(64),
    empreinte_reponse        VARCHAR(128),
    derogation_finance_direction BOOLEAN NOT NULL DEFAULT FALSE,
    id_utilisateur_createur  BIGINT REFERENCES utilisateur(id_utilisateur),
    id_utilisateur_validateur BIGINT REFERENCES utilisateur(id_utilisateur),
    id_employe_cree          BIGINT REFERENCES employe(id_employe),
    id_contrat_cree          BIGINT,
    id_affectation_creee     BIGINT,
    id_onboarding_cree       BIGINT,
    id_document_pdf          BIGINT REFERENCES document_employe(id_document),
    date_creation            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_proposition_candidature_version UNIQUE (id_candidature, version),
    CONSTRAINT chk_proposition_statut CHECK (
        statut IN ('BROUILLON', 'VALIDEE_INTERNE', 'ENVOYEE', 'ACCEPTEE',
                   'REFUSEE', 'CONTRE_PROPOSEE', 'EXPIREE', 'RETIREE')
    ),
    CONSTRAINT chk_proposition_duree CHECK (
        duree_mois IS NULL OR duree_mois > 0
    ),
    CONSTRAINT chk_proposition_periode_essai CHECK (periode_essai_mois >= 0),
    CONSTRAINT chk_proposition_salaire CHECK (salaire_brut_mensuel >= 0),
    CONSTRAINT chk_proposition_version CHECK (version >= 1),
    CONSTRAINT chk_proposition_token CHECK (
        statut <> 'ENVOYEE' OR token_acceptation IS NOT NULL
    )
);

CREATE UNIQUE INDEX uq_proposition_active ON proposition_embauche(id_candidature)
    WHERE active = TRUE;
CREATE INDEX idx_proposition_statut ON proposition_embauche(statut);
CREATE INDEX idx_proposition_candidature ON proposition_embauche(id_candidature);
CREATE INDEX idx_proposition_expiration ON proposition_embauche(date_expiration);

CREATE TABLE version_proposition (
    id_version     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proposition BIGINT NOT NULL REFERENCES proposition_embauche(id_proposition),
    numero_version INTEGER NOT NULL,
    contenu        TEXT NOT NULL,
    id_utilisateur BIGINT REFERENCES utilisateur(id_utilisateur),
    date_creation  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_version_proposition UNIQUE (id_proposition, numero_version),
    CONSTRAINT chk_version_proposition CHECK (numero_version >= 1)
);

CREATE TABLE reponse_candidat (
    id_reponse     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proposition BIGINT NOT NULL REFERENCES proposition_embauche(id_proposition),
    type_reponse   VARCHAR(30) NOT NULL,
    commentaire    TEXT,
    ip             VARCHAR(64),
    empreinte      VARCHAR(128),
    preuve         VARCHAR(255),
    date_reponse   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_reponse_candidat CHECK (
        type_reponse IN ('ACCEPTATION', 'REFUS', 'CONTRE_PROPOSITION')
    )
);

CREATE INDEX idx_reponse_candidat_proposition ON reponse_candidat(id_proposition);

CREATE TABLE historique_proposition (
    id_historique  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proposition BIGINT NOT NULL REFERENCES proposition_embauche(id_proposition),
    id_utilisateur BIGINT REFERENCES utilisateur(id_utilisateur),
    auteur_type    VARCHAR(20) NOT NULL DEFAULT 'UTILISATEUR',
    ancien_statut  VARCHAR(30),
    nouveau_statut VARCHAR(30) NOT NULL,
    motif          TEXT,
    correlation_id VARCHAR(64),
    date_action    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_historique_proposition_auteur CHECK (
        auteur_type IN ('UTILISATEUR', 'CANDIDAT', 'SYSTEME')
    ),
    CONSTRAINT chk_historique_proposition_changement CHECK (
        ancien_statut IS NULL OR ancien_statut <> nouveau_statut
    )
);

CREATE INDEX idx_historique_proposition ON historique_proposition(id_proposition, date_action);

-- ---------------------------------------------------------------------
-- 6. Contrat, affectation et onboarding crees automatiquement a
--    l'acceptation (section 5.4, etapes 4 a 9 ; bloc 4).
-- ---------------------------------------------------------------------
CREATE TABLE contrat (
    id_contrat                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero                     VARCHAR(30) NOT NULL UNIQUE,
    id_employe                 BIGINT NOT NULL REFERENCES employe(id_employe),
    id_proposition             BIGINT REFERENCES proposition_embauche(id_proposition),
    type_contrat               VARCHAR(30) NOT NULL,
    id_contrat_precedent       BIGINT REFERENCES contrat(id_contrat),
    rang                       INTEGER NOT NULL DEFAULT 1,
    date_debut                 DATE NOT NULL,
    date_fin_prevue            DATE,
    date_fin_reelle            DATE,
    fin_periode_essai          DATE,
    salaire_base               NUMERIC(15,2) NOT NULL,
    devise                     VARCHAR(10) NOT NULL DEFAULT 'MGA',
    primes_avantages           TEXT,
    horaires                   TEXT,
    lieu_travail               VARCHAR(150),
    motif_cdd                  TEXT,
    etat                       VARCHAR(20) NOT NULL DEFAULT 'CREE',
    statut_execution           VARCHAR(20) NOT NULL DEFAULT 'A_VENIR',
    date_signature_salarie     TIMESTAMP,
    date_signature_employeur   TIMESTAMP,
    signataire_employeur_id    BIGINT REFERENCES utilisateur(id_utilisateur),
    document_pdf_id            BIGINT REFERENCES document_employe(id_document),
    gabarit_version            VARCHAR(50),
    date_creation              TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    date_modification          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_contrat_etat CHECK (etat IN ('CREE', 'SIGNE', 'VALIDE', 'ANNULE')),
    CONSTRAINT chk_contrat_execution CHECK (
        statut_execution IN ('A_VENIR', 'EN_COURS', 'TERMINE', 'ROMPU', 'SUSPENDU')
    ),
    CONSTRAINT chk_contrat_dates CHECK (
        date_fin_prevue IS NULL OR date_fin_prevue >= date_debut
    ),
    CONSTRAINT chk_contrat_rang CHECK (rang >= 1),
    CONSTRAINT chk_contrat_salaire CHECK (salaire_base >= 0)
);

CREATE INDEX idx_contrat_employe ON contrat(id_employe);
CREATE INDEX idx_contrat_etat ON contrat(etat);

CREATE TABLE affectation (
    id_affectation  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_employe      BIGINT NOT NULL REFERENCES employe(id_employe),
    id_contrat      BIGINT REFERENCES contrat(id_contrat),
    id_poste        BIGINT REFERENCES poste(id_poste),
    id_departement  BIGINT REFERENCES departement(id_departement),
    id_service      BIGINT REFERENCES service(id_service),
    id_manager      BIGINT REFERENCES utilisateur(id_utilisateur),
    lieu_travail    VARCHAR(150),
    horaires        TEXT,
    date_debut      DATE NOT NULL,
    date_fin        DATE,
    taux_activite   INTEGER NOT NULL DEFAULT 100,
    principale      BOOLEAN NOT NULL DEFAULT TRUE,
    motif           VARCHAR(20) NOT NULL DEFAULT 'EMBAUCHE',
    statut          VARCHAR(20) NOT NULL DEFAULT 'PLANIFIEE',
    date_creation   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_affectation_taux CHECK (taux_activite BETWEEN 1 AND 100),
    CONSTRAINT chk_affectation_dates CHECK (date_fin IS NULL OR date_fin >= date_debut),
    CONSTRAINT chk_affectation_motif CHECK (
        motif IN ('EMBAUCHE', 'MUTATION', 'PROMOTION', 'INTERIM', 'REORGANISATION')
    ),
    CONSTRAINT chk_affectation_statut CHECK (
        statut IN ('PLANIFIEE', 'ACTIVE', 'TERMINEE', 'ANNULEE')
    )
);

CREATE INDEX idx_affectation_employe ON affectation(id_employe);
CREATE INDEX idx_affectation_contrat ON affectation(id_contrat);
CREATE UNIQUE INDEX uq_affectation_principale
    ON affectation(id_employe)
    WHERE principale = TRUE AND statut IN ('PLANIFIEE', 'ACTIVE');

CREATE TABLE onboarding (
    id_onboarding        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_employe           BIGINT NOT NULL REFERENCES employe(id_employe),
    id_contrat           BIGINT REFERENCES contrat(id_contrat),
    date_debut           DATE,
    date_cible           DATE,
    id_responsable_rh    BIGINT REFERENCES utilisateur(id_utilisateur),
    statut               VARCHAR(20) NOT NULL DEFAULT 'A_FAIRE',
    progression          INTEGER NOT NULL DEFAULT 0,
    date_creation        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_onboarding_statut CHECK (
        statut IN ('A_FAIRE', 'EN_COURS', 'TERMINE', 'BLOQUE')
    ),
    CONSTRAINT chk_onboarding_progression CHECK (progression BETWEEN 0 AND 100)
);

CREATE INDEX idx_onboarding_employe ON onboarding(id_employe);

CREATE TABLE onboarding_tache (
    id_tache                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_onboarding            BIGINT NOT NULL REFERENCES onboarding(id_onboarding),
    code                     VARCHAR(50) NOT NULL,
    libelle                  VARCHAR(200) NOT NULL,
    categorie                VARCHAR(20) NOT NULL,
    responsable              VARCHAR(100),
    echeance_offset_jours    INTEGER,
    echeance                 DATE,
    obligatoire              BOOLEAN NOT NULL DEFAULT TRUE,
    bloquante                BOOLEAN NOT NULL DEFAULT FALSE,
    id_depend_de             BIGINT REFERENCES onboarding_tache(id_tache),
    statut                   VARCHAR(20) NOT NULL DEFAULT 'A_FAIRE',
    date_fait                DATE,
    id_preuve_document       BIGINT REFERENCES document_employe(id_document),
    date_creation            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_onboarding_tache_code UNIQUE (id_onboarding, code),
    CONSTRAINT chk_onboarding_tache_categorie CHECK (
        categorie IN ('ADMIN', 'IT', 'MATERIEL', 'ACCES', 'FORMATION', 'PAIE', 'SECURITE')
    ),
    CONSTRAINT chk_onboarding_tache_statut CHECK (
        statut IN ('A_FAIRE', 'EN_COURS', 'FAIT', 'NON_APPLICABLE', 'BLOQUE')
    )
);

CREATE INDEX idx_onboarding_tache ON onboarding_tache(id_onboarding);
