-- Bloc 3 - propositions d'embauche et reponses des candidats.
-- V3 reste immuable : cette migration complete sa table.

ALTER TABLE proposition_embauche
    ALTER COLUMN id_proposition_embauche ADD GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE proposition_embauche
    ADD COLUMN id_candidature BIGINT,
    ADD COLUMN type_contrat VARCHAR(20),
    ADD COLUMN salaire_propose NUMERIC(15,2),
    ADD COLUMN lieu_travail VARCHAR(255),
    ADD COLUMN date_debut TIMESTAMP,
    ADD COLUMN date_fin TIMESTAMP,
    ADD COLUMN statut_proposition VARCHAR(30) NOT NULL DEFAULT 'ENVOYEE';

UPDATE proposition_embauche p
SET id_candidature = c.id_candidature
FROM candidature c
WHERE p.id_candidat = c.id_candidat
  AND p.id_offre = c.id_offre
  AND p.id_candidature IS NULL;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM proposition_embauche WHERE id_candidature IS NULL) THEN
        RAISE EXCEPTION 'Une proposition existante ne correspond a aucune candidature';
    END IF;
END $$;

ALTER TABLE proposition_embauche
    ALTER COLUMN id_candidature SET NOT NULL;

ALTER TABLE proposition_embauche
    ADD CONSTRAINT fk_proposition_candidature
        FOREIGN KEY (id_candidature) REFERENCES candidature(id_candidature),
    ADD CONSTRAINT uq_proposition_candidature UNIQUE (id_candidature),
    ADD CONSTRAINT chk_proposition_type_contrat
        CHECK (type_contrat IS NULL OR type_contrat IN ('CDI', 'CDD')),
    ADD CONSTRAINT chk_proposition_salaire
        CHECK (salaire_propose IS NULL OR salaire_propose >= 0),
    ADD CONSTRAINT chk_proposition_dates
        CHECK (date_fin IS NULL OR (date_debut IS NOT NULL AND date_fin >= date_debut)),
    ADD CONSTRAINT chk_proposition_cdd_date_fin
        CHECK (type_contrat <> 'CDD' OR date_fin IS NOT NULL),
    ADD CONSTRAINT chk_proposition_statut
        CHECK (statut_proposition IN ('ENVOYEE', 'ACCEPTEE', 'REFUSEE', 'AJUSTEMENT_DEMANDE'));

CREATE INDEX idx_proposition_candidature ON proposition_embauche(id_candidature);
CREATE INDEX idx_proposition_statut ON proposition_embauche(statut_proposition);

CREATE TABLE reponse_proposition (
    id_reponse BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proposition_embauche INT NOT NULL REFERENCES proposition_embauche(id_proposition_embauche),
    id_candidat BIGINT NOT NULL REFERENCES candidat(id_candidat),
    decision VARCHAR(30) NOT NULL,
    salaire_souhaite NUMERIC(15,2),
    lieu_souhaite VARCHAR(255),
    type_contrat_souhaite VARCHAR(20),
    date_debut_souhaitee TIMESTAMP,
    date_fin_souhaitee TIMESTAMP,
    commentaire TEXT,
    date_reponse TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_reponse_decision
        CHECK (decision IN ('ACCEPTEE', 'REFUSEE', 'AJUSTEMENT_DEMANDE')),
    CONSTRAINT chk_reponse_salaire
        CHECK (salaire_souhaite IS NULL OR salaire_souhaite >= 0),
    CONSTRAINT chk_reponse_type_contrat
        CHECK (type_contrat_souhaite IS NULL OR type_contrat_souhaite IN ('CDI', 'CDD')),
    CONSTRAINT chk_reponse_dates
        CHECK (date_fin_souhaitee IS NULL
            OR (date_debut_souhaitee IS NOT NULL AND date_fin_souhaitee >= date_debut_souhaitee))
);

CREATE INDEX idx_reponse_proposition ON reponse_proposition(id_proposition_embauche);
